# Variable = a container for a value (string, integer, boolean, float.)
#            a variable behaves as if it was the value it contains.

# String = sequence of characters
first_name = "Alex" 
print(first_name)       # prints the value of the variable
print(f'my name is {first_name}') # using variable in a formatted string

# Integer = whole number
age = 22
print(f'I am {age} years old')

# Float = number with a decimal point
height = 6.1
print(f'I am {height} feet tall')

# Boolean = True or False value
straight = True

# Conditional statement using boolean variable
if straight:
    print(f'It is {straight} that I am straight')
else:
    print(f'It is {straight} that I am straight')